import { ref, computed } from "vue";

export type Lang = "zh" | "en";

const currentLang = ref<Lang>(
  (localStorage.getItem("ft-lang") as Lang) || "zh"
);

export function useLang() {
  function setLang(lang: Lang) {
    currentLang.value = lang;
    localStorage.setItem("ft-lang", lang);
  }

  function toggleLang() {
    setLang(currentLang.value === "zh" ? "en" : "zh");
  }

  const t = computed(() => messages[currentLang.value]);

  return { lang: currentLang, setLang, toggleLang, t };
}

